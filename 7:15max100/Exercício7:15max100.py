'''. Exercício 7: Celsius para Fahrenheit - Leia uma temperatura em graus celsius e mostre o valor equivalente em Fahrenheit.
'''
valor1 = float(input(' Digite um valor: '))
celsius = valor1
fahrenheit = celsius * 1.8 + 32
print(' {0} em graus celsius equivalem a {1} graus fahrenheit. '.format(celsius, fahrenheit))