''' Escreva um programa que leia dois números inteiros e mostre a soma deles.  
Exemplo de execução:
Primeiro valor: 8 
Segundo valor: 5    
Soma: 13
'''

primeiroValor = int(input("Primeiro valor: "))
segundoValor = int(input("Segundo valor: "))
soma = primeiroValor + segundoValor
print("Soma: {0}".format(soma))
